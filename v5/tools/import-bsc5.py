#!/usr/bin/env python3
"""Import real J2000 BSC5 stars with 4.5 < V <= 6.0; no sky seed or synthesis.

python3 -I tools/import-bsc5.py [--download]
The checked-in original CDS catalogue makes normal regeneration offline.
"""
import argparse
from collections import Counter
import gzip
import hashlib
import json
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'bsc5-catalog.gz': ('https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz',
                        '3dc44b1e90be8fbe5bcc7656032560f51275f985c7e3f783c9028e1838ec7bed'),
    'bsc5-ReadMe.txt': ('https://cdsarc.cds.unistra.fr/ftp/V/50/ReadMe',
                       '44fd9c73e2eecad0beb47bdfa3f01c60fd43f93d6964198e31fcd48732de5b33'),
}


def import_catalog(download=False):
    for filename, (url, checksum) in SOURCES.items():
        path = ROOT / 'data' / filename
        if download:
            data = urlopen(url, timeout=60).read()
            if hashlib.sha256(data).hexdigest() != checksum:
                raise ValueError(f'Changed source at {url}; inspect before replacing checked-in data')
            path.parent.mkdir(exist_ok=True)
            path.write_bytes(data)
        if hashlib.sha256(path.read_bytes()).hexdigest() != checksum:
            raise ValueError(f'Source checksum mismatch: {path}')
    lines = gzip.decompress((ROOT / 'data/bsc5-catalog.gz').read_bytes()).decode('ascii').splitlines()
    assert len(lines) == 9110
    all_hr = [int(line[:4]) for line in lines]
    assert len(set(all_hr)) == 9110 and min(all_hr) == 1 and max(all_hr) == 9110
    selected, missing, valid = [], [], 0
    for line in lines:
        hr = int(line[:4])
        if not line[75:90].strip() or not line[102:107].strip():
            missing.append(hr)
            continue
        # One-indexed CDS columns: RA 76–83, Dec 84–90, Vmag 103–107.
        ra = (int(line[75:77]) + int(line[77:79]) / 60 + float(line[79:83]) / 3600) * 15
        dec = (int(line[84:86]) + int(line[86:88]) / 60 + int(line[88:90]) / 3600) * (-1 if line[83] == '-' else 1)
        mag = float(line[102:107])
        assert 0 <= ra < 360 and -90 <= dec <= 90 and line[83] in '+-'
        valid += 1
        if 4.5 < mag <= 6.0:
            selected.append([hr, line[4:14].strip(), round(ra, 7), round(dec, 7), mag, line[107:108].strip()])
    assert valid == 9096 and len(missing) == 14 and len(selected) == 4176
    by_hr = {row[0]: row for row in selected}
    assert len(by_hr) == len(selected)
    # Independent sexagesimal computations for faint named stars from source rows.
    known = {6116: ((16 + 17 / 60 + 30.3 / 3600) * 15, 75 + 45 / 60 + 19 / 3600, 4.95),
             6554: ((17 + 32 / 60 + 10.6 / 3600) * 15, 55 + 11 / 60 + 3 / 3600, 4.88),
             6555: ((17 + 32 / 60 + 16.0 / 3600) * 15, 55 + 10 / 60 + 23 / 3600, 4.87)}
    for hr, expected in known.items():
        assert all(abs(value - match) < 1e-7 for value, match in zip(by_hr[hr][2:5], expected)), hr
    coordinate_counts = Counter((row[2], row[3]) for row in selected)
    stats = {'sourceRecords': len(lines), 'validJ2000Stars': valid, 'missingHR': missing,
             'selectedStars': len(selected), 'uniqueHR': len(by_hr),
             'uniquePositions': len(coordinate_counts),
             'duplicatePositionGroups': sum(n > 1 for n in coordinate_counts.values()),
             'northOfMinus43': sum(row[3] >= -43 for row in selected),
             'raDegRange': [min(row[2] for row in selected), max(row[2] for row in selected)],
             'decDegRange': [min(row[3] for row in selected), max(row[3] for row in selected)],
             'magRange': [min(row[4] for row in selected), max(row[4] for row in selected)]}
    assert stats['uniquePositions'] == 4169 and stats['duplicatePositionGroups'] == 7
    metadata = {'catalogue': 'CDS/VizieR V/50 (Hoffleit & Warren 1991)', 'epoch': 'J2000.0',
                'sourceURL': SOURCES['bsc5-catalog.gz'][0], 'sourceSHA256': SOURCES['bsc5-catalog.gz'][1],
                'selection': '4.5 < Vmag <= 6.0; full sky; no declination cutoff', 'stats': stats}
    js = ('// Generated by python3 -I tools/import-bsc5.py; original CDS BSC5, J2000.\n'
          '// Attribution and licence limits: docs/evidence/bsc5-provenance.md.\n'
          '(function (root) {\n  "use strict";\n'
          '  // [HR, original catalogue name, RA degrees, Dec degrees, Vmag, Vmag origin code]\n'
          '  const rows = ' + json.dumps(selected, separators=(',', ':')) + ';\n'
          '  const stars = rows.map(([hr,name,raDeg,dec,mag,magCode]) => '
          'Object.freeze({hr,id:`HR${hr}`,name,raDeg,ra:raDeg/15,dec,mag,magCode}));\n'
          '  const byHR = Object.fromEntries(stars.map(s => [s.hr,s]));\n'
          '  const api = Object.freeze({stars:Object.freeze(stars),byHR:Object.freeze(byHR),metadata:'
          + json.dumps(metadata, separators=(',', ':')) + '});\n'
          '  root.KaliFaintStars = api;\n'
          '  if (typeof module !== "undefined" && module.exports) module.exports = api;\n'
          '})(typeof globalThis !== "undefined" ? globalThis : this);\n')
    (ROOT / 'stars-faint.js').write_text(js)
    print(json.dumps(stats, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--download', action='store_true')
    import_catalog(parser.parse_args().download)
